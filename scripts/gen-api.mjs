// FastAPI OpenAPI schema -> packages/api-types/{openapi.json, src/schema.ts}
// Run with `pnpm gen:api`. Python runs in the api container (see docker-compose.yml);
// set KIFORGE_HOST_PYTHON=1 to use `uv run` directly (CI, or a machine where native wheels load).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = resolve(root, 'packages/api-types');
const exportCmd = ['uv', 'run', '--no-sync', 'python', '-m', 'app.tools.export_openapi'];

const capture = (cmd, args, cwd) =>
  execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });

const raw = process.env.KIFORGE_HOST_PYTHON
  ? capture(exportCmd[0], exportCmd.slice(1), resolve(root, 'services/api'))
  : capture('docker', ['compose', 'run', '--rm', '--no-deps', '-T', 'api', ...exportCmd], root);
const schema = JSON.parse(raw);
writeFileSync(resolve(pkg, 'openapi.json'), JSON.stringify(schema, null, 2) + '\n');

// openapi-typescript is a dev dependency of @kiforge/api-types; resolve it from there.
const require = createRequire(resolve(pkg, 'package.json'));
// require.resolve picks the CommonJS build, whose exports arrive wrapped in `default`.
const mod = await import(pathToFileURL(require.resolve('openapi-typescript')).href);
const lib = mod.default ?? mod;
const openapiTS = lib.default ?? lib;
const { astToString } = lib;
const ast = await openapiTS(schema);
const header = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';
writeFileSync(resolve(pkg, 'src/schema.ts'), header + astToString(ast));
console.log('wrote packages/api-types/openapi.json and src/schema.ts');
