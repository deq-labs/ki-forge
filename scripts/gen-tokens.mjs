// design/tokens.json -> apps/mobile/src/theme/tokens.ts
// Run with `pnpm gen:tokens`. Never hand-edit the output; CI fails if it is stale.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'design/tokens.json');
const out = resolve(root, 'apps/mobile/src/theme/tokens.ts');
const tokens = JSON.parse(readFileSync(src, 'utf8'));
const THEME = 'night';

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => {
  const m = /^(-?[\d.]+)px$/.exec(String(v));
  if (!m) throw new Error(`expected a px value, got ${v}`);
  return Number(m[1]);
};

// Colors
const colors = {};
const pathColors = {};
for (const t of tokens.color.tokens) {
  const value = t.value[THEME];
  if (!value) throw new Error(`color ${t.name} has no "${THEME}" value`);
  colors[camel(t.name)] = value;
  const path = /^path-([a-z]+)(-2)?$/.exec(t.name);
  if (path) {
    pathColors[path[1]] ??= {};
    pathColors[path[1]][path[2] ? 'kiHot' : 'ki'] = value;
  }
}

// Type
const fontFamilies = { ...tokens.type.families };
const typography = {};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const fontSize = px(s.fontSize);
    const style = {
      family: group.family,
      fontSize,
      lineHeight: px(s.lineHeight),
      fontWeight: String(s.fontWeight),
    };
    if (s.letterSpacing) {
      const em = /^(-?[\d.]+)em$/.exec(s.letterSpacing);
      style.letterSpacing = em ? Math.round(Number(em[1]) * fontSize * 100) / 100 : px(s.letterSpacing);
    }
    if (group.family === 'data') style.fontVariant = ['tabular-nums'];
    typography[camel(s.name)] = style;
  }
}

const scale = (list, prefix) =>
  Object.fromEntries(list.map((t) => [t.name.replace(prefix, ''), px(t.value)]));
const spacing = scale(tokens.spacing.tokens, 'space-');
const radius = scale(tokens.radius.tokens, 'radius-');
// React Native (new architecture) accepts CSS box-shadow strings via the `boxShadow` style prop.
const shadow = Object.fromEntries(tokens.shadow.tokens.map((t) => [camel(t.name.replace('shadow-', '')), t.value]));

const block = (name, value, type = '') =>
  `export const ${name}${type} = ${JSON.stringify(value, null, 2)} as const;\n`;

const ts = `// GENERATED by scripts/gen-tokens.mjs from design/tokens.json. Do not edit; run \`pnpm gen:tokens\`.
// Theme: ${THEME} (${tokens.name} v${tokens.version})

${block('colors', colors)}
/** Each path's energy pair; the ThemeProvider re-points \`ki\` / \`kiHot\` to the active path. */
${block('pathColors', pathColors)}
/** CSS font stacks (web). Native font names are mapped when fonts load (M3). */
${block('fontFamilies', fontFamilies)}
${block('typography', typography)}
${block('spacing', spacing)}
${block('radius', radius)}
${block('shadow', shadow)}
export type ColorToken = keyof typeof colors;
export type PathSlug = keyof typeof pathColors;
export type TypographyToken = keyof typeof typography;
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, ts);
console.log(`wrote ${out.replace(root + '\\', '').replace(root + '/', '')}`);
